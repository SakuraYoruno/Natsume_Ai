export const legacyRedirects = routeManifest.flatMap((route) =>
  (route.legacyPaths || []).map((legacyPath) => ({
    from: legacyPath,
    to: route.path.replace('/*', ''),
  })),
)

export const NAV_SECTIONS = ROUTE_NAV_GROUPS
  .map((title) => ({
    title,
    items: routeManifest
      .filter((route) => route.navGroup === title && !route.hiddenFromNav)
      .map((route) => ({
        to: route.path.replace('/*', ''),
        icon: route.icon,
        label: route.label,
      })),
  }))
  .filter((section) => section.items.length > 0)
