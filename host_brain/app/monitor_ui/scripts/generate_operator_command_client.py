"""Generate the Monitor UI Operator Command client from the Host OpenAPI source."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys


UI_ROOT = Path(__file__).resolve().parents[1]
REPOSITORY_ROOT = Path(__file__).resolve().parents[4]
OPENAPI_OUTPUT = UI_ROOT / "src/shared/api/generated/operator-command.openapi.json"
CLIENT_OUTPUT = UI_ROOT / "src/shared/api/generated/operatorCommandClient.ts"


def _load_openapi() -> dict[str, object]:
    sys.path.insert(0, str(REPOSITORY_ROOT))
    from host_brain.observability.command_http import (  # noqa: PLC0415
        build_operator_command_openapi,
    )

    return build_operator_command_openapi()


def _command_specs(document: dict[str, object]) -> dict[str, object]:
    specs: dict[str, object] = {}
    for path, item in sorted(dict(document["paths"]).items()):
        operation = dict(item)["post"]
        command_id = str(operation["x-natsume-command-id"])
        envelope = operation["requestBody"]["content"]["application/json"]["schema"]
        specs[command_id] = {
            "action": operation["x-natsume-action"],
            "path": path,
            "payloadSchema": envelope["properties"]["payload"],
            "requiredScopes": operation["x-natsume-required-scopes"],
        }
    return specs


def _render_client(document: dict[str, object]) -> str:
    specs = json.dumps(
        _command_specs(document),
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    )
    return f'''// Generated by scripts/generate_operator_command_client.py. Do not edit.
// Contract-only browser artifact: server BFF owns all credentials and signing.
export const OPERATOR_COMMAND_SPECS = {specs} as const

export type OperatorCommandId = keyof typeof OPERATOR_COMMAND_SPECS
export type OperatorCommandReceipt = {{
  allowed: boolean
  command_id: string
  duplicate: boolean
  executed: boolean
  reason_code: string
  status: 'completed' | 'duplicate' | 'rejected' | 'conflict' | 'uncertain' | 'unavailable' | 'shadow'
  audit_ref?: string
  claim_ref?: string
  result_ref?: string
  terminal_state?: string
  certainty?: string
}}

export class OperatorCommandContractError extends Error {{
  readonly reasonCode: string

  constructor(reasonCode: string) {{
    super(reasonCode)
    this.name = 'OperatorCommandContractError'
    this.reasonCode = reasonCode
  }}
}}

export function isOperatorCommandId(value: string): value is OperatorCommandId {{
  return Object.prototype.hasOwnProperty.call(OPERATOR_COMMAND_SPECS, value)
}}

export function validateOperatorCommandPayload(
  commandId: OperatorCommandId,
  payload: Record<string, unknown>,
): void {{
  const spec = OPERATOR_COMMAND_SPECS[commandId]
  validatePayload(spec.payloadSchema, payload)
}}

function validatePayload(schema: any, payload: Record<string, unknown>): void {{
  if (!payload || typeof payload !== 'object' || Array.isArray(payload)) {{
    throw new OperatorCommandContractError('OPERATOR_COMMAND_PAYLOAD_INVALID')
  }}
  const properties = schema.properties || {{}}
  const required = schema.required || []
  if (required.some((field: string) => !Object.prototype.hasOwnProperty.call(payload, field))) {{
    throw new OperatorCommandContractError('OPERATOR_COMMAND_PAYLOAD_REQUIRED')
  }}
  for (const [field, value] of Object.entries(payload)) {{
    const fieldSchema = properties[field]
    if (!fieldSchema) throw new OperatorCommandContractError('OPERATOR_COMMAND_PAYLOAD_FIELD_DENIED')
    if (value == null) continue
    const actual = Array.isArray(value) ? 'array' : typeof value
    if (fieldSchema.type === 'integer' && (!Number.isInteger(value) || typeof value !== 'number')) {{
      throw new OperatorCommandContractError('OPERATOR_COMMAND_PAYLOAD_TYPE_INVALID')
    }}
    if (fieldSchema.type === 'number' && (typeof value !== 'number' || !Number.isFinite(value))) {{
      throw new OperatorCommandContractError('OPERATOR_COMMAND_PAYLOAD_TYPE_INVALID')
    }}
    if (fieldSchema.type && !['integer', 'number'].includes(fieldSchema.type) && actual !== fieldSchema.type) {{
      throw new OperatorCommandContractError('OPERATOR_COMMAND_PAYLOAD_TYPE_INVALID')
    }}
  }}
}}

export function validateOperatorCommandReceipt(
  receipt: OperatorCommandReceipt,
  commandId: OperatorCommandId,
): void {{
  if (!receipt || typeof receipt !== 'object' || receipt.command_id !== commandId ||
      typeof receipt.allowed !== 'boolean' || typeof receipt.executed !== 'boolean' ||
      typeof receipt.duplicate !== 'boolean' || !receipt.reason_code || !receipt.status) {{
    throw new OperatorCommandContractError('OPERATOR_COMMAND_RECEIPT_INVALID')
  }}
  if (receipt.status === 'completed' && (!receipt.audit_ref || !receipt.claim_ref)) {{
    throw new OperatorCommandContractError('OPERATOR_COMMAND_RECEIPT_NOT_DURABLE')
  }}
}}
'''


def _render_openapi(document: dict[str, object]) -> str:
    return json.dumps(document, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def _check_or_write(path: Path, content: str, *, check: bool) -> bool:
    if check:
        return path.is_file() and path.read_text(encoding="utf-8") == content
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    return True


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    document = _load_openapi()
    outputs = {
        OPENAPI_OUTPUT: _render_openapi(document),
        CLIENT_OUTPUT: _render_client(document),
    }
    stale = [
        str(path.relative_to(UI_ROOT))
        for path, content in outputs.items()
        if not _check_or_write(path, content, check=args.check)
    ]
    if stale:
        print("Operator command generated artifacts drifted: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
