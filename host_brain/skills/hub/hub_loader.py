"""Skills Hub 加载器 — 扫描 skills 目录，自动发现并注册外部 Skill。

扫描逻辑：
1. 遍历 HUB_SKILLS_DIR 下的每个子目录
2. 查找 SKILL.md → 解析为 SkillManifest
3. 查找 provider.py → 如有则使用手写 Provider（SKILL_PROVIDER_CLASS）
4. 查找 executor.py → 如有则自动注册到 ToolExecutorRegistry
5. 如无 provider.py，从 SKILL.md 自动生成 DeclarativeSkillSpec
6. 注册到 SkillRegistry

目录约定：
  skills/
  ├── weather-query/
  │   ├── SKILL.md           ← 必须
  │   ├── provider.py        ← 可选（手写 Provider）
  │   ├── executor.py        ← 可选（自定义执行器）
  │   ├── scripts/           ← 可选（辅助脚本）
  │   └── references/        ← 可选（参考文档）
  └── music-player/
      ├── SKILL.md
      └── ...
"""

from __future__ import annotations

import importlib
import inspect
import json
import logging
import os
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable

from host_brain.skills.declarative import DeclarativeSkillProvider, DeclarativeSkillSpec
from host_brain.skills.hub.manifest_parser import SkillManifest, parse_skill_md
from host_brain.skills.registry import SkillRegistry

logger = logging.getLogger(__name__)

# 默认 Hub Skills 目录（可通过环境变量覆盖）
_DEFAULT_HUB_DIR = Path(__file__).resolve().parent  # host_brain/skills/hub/
SKILL_MD_FILENAME = "SKILL.md"
PROVIDER_FILENAME = "provider.py"
EXECUTOR_FILENAME = "executor.py"
LOCK_FILENAME = ".natsume-skills-lock.json"


def _resolve_hub_skills_dir() -> Path:
    """解析 Hub Skills 目录路径。

    优先级：
    1. HOST_SKILL_HUB_DIR 环境变量
    2. 默认 host_brain/skills/hub/
    """
    env_dir = os.environ.get("HOST_SKILL_HUB_DIR", "").strip()
    if env_dir:
        return Path(env_dir).resolve()
    return _DEFAULT_HUB_DIR


@dataclass
class HubSkillInfo:
    """单个 Hub Skill 的加载信息。"""
    name: str
    version: str
    source_dir: str
    status: str  # "REGISTERED" / "SKIPPED" / "ERROR"
    provider_type: str  # "auto_generated" / "custom_provider" / "skipped"
    has_executor: bool
    skill_names: list[str] = field(default_factory=list)
    error: str | None = None


@dataclass
class HubLoadResult:
    """Hub 加载总结果。"""
    skills_dir: str
    total_dirs_scanned: int
    registered_count: int
    skipped_count: int
    error_count: int
    skills: list[HubSkillInfo] = field(default_factory=list)
    ts_ms: int = 0


def _identity_normalizer(args: dict[str, Any], ctx: dict[str, Any] | None) -> dict[str, Any]:
    """默认参数归一化器（透传所有参数）。"""
    payload: dict[str, Any] = {}
    payload.update(dict(args or {}))
    if ctx:
        payload["_context"] = ctx
        payload.setdefault("request_id", str(ctx.get("request_id") or "").strip() or None)
        payload.setdefault("session_id", str(ctx.get("session_id") or "").strip() or None)
    payload.setdefault("manifest_ref", f"hub_skill::{payload.get('action', 'run')}")
    return payload


def _generate_provider_from_manifest(manifest: SkillManifest) -> DeclarativeSkillProvider:
    """从 SkillManifest 自动生成 DeclarativeSkillProvider。"""
    spec = DeclarativeSkillSpec(
        skill_name=manifest.name,
        clearance=manifest.clearance,
        risk_level=manifest.risk_level,
        scope=manifest.scope,
        reversible=manifest.reversible,
        require_confirm=manifest.require_confirm,
        description=manifest.description,
        tool=manifest.tool,
        action=manifest.action,
        normalize_args=_identity_normalizer,
    )

    class _AutoGeneratedProvider(DeclarativeSkillProvider):
        skill_specs = (spec,)

    _AutoGeneratedProvider.__name__ = f"AutoProvider_{manifest.name}"
    _AutoGeneratedProvider.__qualname__ = _AutoGeneratedProvider.__name__
    return _AutoGeneratedProvider()


def _load_custom_provider(skill_dir: Path) -> Any | None:
    """尝试从 skill 目录加载 provider.py 中的 SKILL_PROVIDER_CLASS。"""
    provider_file = skill_dir / PROVIDER_FILENAME
    if not provider_file.exists():
        return None

    module_name = f"_natsume_hub_skill_{skill_dir.name.replace('-', '_')}_provider"
    try:
        # 确保 skill 目录在 sys.path 中
        skill_dir_str = str(skill_dir)
        if skill_dir_str not in sys.path:
            sys.path.insert(0, skill_dir_str)

        # 清除旧缓存
        importlib.invalidate_caches()
        sys.modules.pop(module_name, None)

        # 使用 spec 加载（不污染全局命名空间）
        import importlib.util

        spec = importlib.util.spec_from_file_location(module_name, str(provider_file))
        if spec is None or spec.loader is None:
            logger.warning("Hub: 无法创建 module spec: %s", provider_file)
            return None
        module = importlib.util.module_from_spec(spec)
        sys.modules[module_name] = module
        spec.loader.exec_module(module)

        provider_cls = getattr(module, "SKILL_PROVIDER_CLASS", None)
        if provider_cls is None:
            logger.warning("Hub: provider.py 缺少 SKILL_PROVIDER_CLASS: %s", provider_file)
            return None
        if not inspect.isclass(provider_cls):
            logger.warning("Hub: SKILL_PROVIDER_CLASS 不是类: %s", provider_file)
            return None
        return provider_cls()
    except Exception as exc:
        logger.warning("Hub: provider.py 加载失败 (%s): %s", provider_file, exc)
        return None


def _load_custom_executor(
    skill_dir: Path,
    tool_name: str,
) -> Callable[[dict[str, Any]], Any] | None:
    """尝试从 skill 目录加载 executor.py 中的 execute 函数。

    约定：executor.py 必须导出 `execute(payload: dict) -> Any` 函数。
    """
    executor_file = skill_dir / EXECUTOR_FILENAME
    if not executor_file.exists():
        return None

    module_name = f"_natsume_hub_skill_{skill_dir.name.replace('-', '_')}_executor"
    try:
        skill_dir_str = str(skill_dir)
        if skill_dir_str not in sys.path:
            sys.path.insert(0, skill_dir_str)

        importlib.invalidate_caches()
        sys.modules.pop(module_name, None)

        import importlib.util

        spec = importlib.util.spec_from_file_location(module_name, str(executor_file))
        if spec is None or spec.loader is None:
            return None
        module = importlib.util.module_from_spec(spec)
        sys.modules[module_name] = module
        spec.loader.exec_module(module)

        executor_fn = getattr(module, "execute", None)
        if executor_fn is None:
            executor_fn = getattr(module, f"execute_{tool_name}", None)
        if executor_fn is None:
            logger.warning("Hub: executor.py 缺少 execute() 函数: %s", executor_file)
            return None
        if not callable(executor_fn):
            return None
        return executor_fn
    except Exception as exc:
        logger.warning("Hub: executor.py 加载失败 (%s): %s", executor_file, exc)
        return None


def load_hub_skills(
    registry: SkillRegistry,
    *,
    executor_registry: Any | None = None,
    skills_dir: Path | None = None,
) -> HubLoadResult:
    """扫描 Hub Skills 目录，注册所有发现的 Skill。

    Args:
        registry: SkillRegistry 实例
        executor_registry: ToolExecutorRegistry 实例（可选，用于注册自定义 executor）
        skills_dir: skills 目录路径（可选，默认从环境变量/默认路径解析）

    Returns:
        HubLoadResult 加载结果汇总
    """
    hub_dir = skills_dir or _resolve_hub_skills_dir()
    result = HubLoadResult(
        skills_dir=str(hub_dir),
        total_dirs_scanned=0,
        registered_count=0,
        skipped_count=0,
        error_count=0,
        ts_ms=int(time.time() * 1000),
    )

    if not hub_dir.exists() or not hub_dir.is_dir():
        logger.info("Hub: skills 目录不存在，跳过: %s", hub_dir)
        return result

    # 遍历子目录
    for item in sorted(hub_dir.iterdir()):
        if not item.is_dir():
            continue
        if item.name.startswith(("_", ".")):
            continue

        skill_md = item / SKILL_MD_FILENAME
        if not skill_md.exists():
            continue

        result.total_dirs_scanned += 1
        info = _load_single_skill(
            skill_dir=item,
            skill_md=skill_md,
            registry=registry,
            executor_registry=executor_registry,
        )
        result.skills.append(info)

        if info.status == "REGISTERED":
            result.registered_count += 1
        elif info.status == "ERROR":
            result.error_count += 1
        else:
            result.skipped_count += 1

    if result.registered_count > 0:
        logger.info(
            "Hub: 加载完成 dir=%s scanned=%d registered=%d skipped=%d errors=%d",
            hub_dir,
            result.total_dirs_scanned,
            result.registered_count,
            result.skipped_count,
            result.error_count,
        )

    return result


def _load_single_skill(
    *,
    skill_dir: Path,
    skill_md: Path,
    registry: SkillRegistry,
    executor_registry: Any | None,
) -> HubSkillInfo:
    """加载单个 skill 目录。"""
    try:
        manifest = parse_skill_md(skill_md)
    except Exception as exc:
        return HubSkillInfo(
            name=skill_dir.name,
            version="",
            source_dir=str(skill_dir),
            status="ERROR",
            provider_type="skipped",
            has_executor=False,
            error=f"SKILL.md parse error: {exc}",
        )

    errors = manifest.validate()
    if errors:
        return HubSkillInfo(
            name=manifest.name,
            version=manifest.version,
            source_dir=str(skill_dir),
            status="ERROR",
            provider_type="skipped",
            has_executor=False,
            error=f"validation errors: {'; '.join(errors)}",
        )

    # 检查是否已注册（避免重复）
    if registry.get(manifest.name) is not None:
        return HubSkillInfo(
            name=manifest.name,
            version=manifest.version,
            source_dir=str(skill_dir),
            status="SKIPPED",
            provider_type="skipped",
            has_executor=False,
            error=f"skill already registered: {manifest.name}",
        )

    # 尝试加载自定义 executor
    has_executor = False
    executor_fn = _load_custom_executor(skill_dir, manifest.tool)
    if executor_fn is not None and executor_registry is not None:
        try:
            # 注册到 ToolExecutorRegistry
            from host_brain.skills.executor_registry import ToolExecutorSpec  # noqa: PLC0415

            executor_registry.register(ToolExecutorSpec(
                tool_name=manifest.tool,
                handler=executor_fn,
            ))
            has_executor = True
            logger.info("Hub: executor registered tool=%s from %s", manifest.tool, skill_dir)
        except ValueError:
            # 已存在同名 executor，跳过
            has_executor = True
            logger.debug("Hub: executor already exists tool=%s", manifest.tool)
        except Exception as exc:
            logger.warning("Hub: executor registration failed tool=%s: %s", manifest.tool, exc)

    # 尝试加载自定义 provider
    provider_type = "auto_generated"
    skill_names: list[str] = []
    try:
        custom_provider = _load_custom_provider(skill_dir)
        if custom_provider is not None:
            count = registry.register_decorated(custom_provider)
            provider_type = "custom_provider"
            # 提取注册的 skill 名称
            declarative_entries = getattr(custom_provider, "__skill_meta_entries__", None)
            if callable(declarative_entries):
                skill_names = [e.skill_name for e in declarative_entries()]
            else:
                skill_names = [manifest.name]
            logger.info(
                "Hub: custom provider registered skill=%s count=%d from %s",
                manifest.name, count, skill_dir,
            )
        else:
            # 从 SKILL.md 自动生成 provider
            auto_provider = _generate_provider_from_manifest(manifest)
            registry.register_decorated(auto_provider)
            skill_names = [manifest.name]
            logger.info(
                "Hub: auto-generated provider registered skill=%s from %s",
                manifest.name, skill_dir,
            )
    except Exception as exc:
        return HubSkillInfo(
            name=manifest.name,
            version=manifest.version,
            source_dir=str(skill_dir),
            status="ERROR",
            provider_type=provider_type,
            has_executor=has_executor,
            error=f"registration failed: {exc}",
        )

    return HubSkillInfo(
        name=manifest.name,
        version=manifest.version,
        source_dir=str(skill_dir),
        status="REGISTERED",
        provider_type=provider_type,
        has_executor=has_executor,
        skill_names=skill_names,
    )


# ── Lock File 管理 ────────────────────────────────────────────────────────

def read_lock_file(skills_dir: Path | None = None) -> dict[str, Any]:
    """读取 skills lock 文件。"""
    hub_dir = skills_dir or _resolve_hub_skills_dir()
    lock_path = hub_dir / LOCK_FILENAME
    if not lock_path.exists():
        return {}
    try:
        return json.loads(lock_path.read_text(encoding="utf-8"))
    except Exception:
        return {}


def write_lock_file(data: dict[str, Any], skills_dir: Path | None = None) -> None:
    """写入 skills lock 文件。"""
    hub_dir = skills_dir or _resolve_hub_skills_dir()
    hub_dir.mkdir(parents=True, exist_ok=True)
    lock_path = hub_dir / LOCK_FILENAME
    lock_path.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


def update_lock_entry(
    name: str,
    version: str,
    source: str,
    *,
    skills_dir: Path | None = None,
) -> None:
    """更新 lock 文件中的单个条目。"""
    lock = read_lock_file(skills_dir)
    lock[name] = {
        "version": version,
        "source": source,
        "installed_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
    }
    write_lock_file(lock, skills_dir)


def remove_lock_entry(name: str, *, skills_dir: Path | None = None) -> bool:
    """从 lock 文件中移除条目。"""
    lock = read_lock_file(skills_dir)
    if name not in lock:
        return False
    del lock[name]
    write_lock_file(lock, skills_dir)
    return True
